export type SyllabusVerificationStatus = 'PASS' | 'PENDING';

export interface VerifiedTextbookChapterItem {
  chapterNumber: number;
  chapterTitle: string;
  sectionOrPart?: string;
}

export interface VerifiedSubjectSyllabusEntry {
  board: EducationBoard;
  classLevel: ClassLevel;
  subject: SubjectName;
  status: SyllabusVerificationStatus;
  textbookTitle: string;
  publisher: string;
  academicYearEdition: string;
  applicableMediums: InstructionMedium[];
  verificationNote: string;
  chapters: VerifiedTextbookChapterItem[];
}

function toChapters(titles: string[], sectionOrPart?: string): VerifiedTextbookChapterItem[] {
  return titles.map((chapterTitle, idx) => ({
    chapterNumber: idx + 1,
    chapterTitle,
    ...(sectionOrPart ? { sectionOrPart } : {}),
  }));
}

