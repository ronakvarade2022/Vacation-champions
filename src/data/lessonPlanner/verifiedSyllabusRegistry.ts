export function getVerifiedSubjectSyllabus(
  board: EducationBoard,
  classLevel: ClassLevel,
  subject: SubjectName
): VerifiedSubjectSyllabusEntry {
  const key = `${board}__${classLevel}__${subject}`;
  const found = VERIFIED_ENTRIES_MAP[key];
  if (found) {
    return {
      board,
      classLevel,
      subject,
      ...found,
    };
  }

  const pendingNote =
    board === 'ICSE'
      ? 'PENDING: CISCE provides curriculum themes, while the exact textbook index depends on the individual ICSE school’s prescribed publisher textbook.'
      : 'PENDING: Official medium-specific textbook index or non-board enrichment syllabus awaits direct textbook index verification.';

  return {
    board,
    classLevel,
    subject,
    status: 'PENDING',
    textbookTitle: 'PENDING VERIFICATION',
    publisher:
      board === 'Maharashtra'
        ? 'Balbharati, Pune'
        : board === 'CBSE'
        ? 'NCERT, New Delhi'
        : 'CISCE / School-Prescribed Publisher',
    academicYearEdition: 'PENDING VERIFICATION',
    applicableMediums: ['English', 'Marathi', 'Hindi', 'Semi-English'],
    verificationNote: pendingNote,
    chapters: [],
  };
}

export function getAllVerifiedSyllabusEntries(): VerifiedSubjectSyllabusEntry[] {
  const boards: EducationBoard[] = ['Maharashtra', 'CBSE', 'ICSE'];
  const entries: VerifiedSubjectSyllabusEntry[] = [];

  for (const board of boards) {
    for (const classLevel of ALL_10_CLASSES) {
      const subjects = getSubjectsForClass(classLevel, board);
      for (const subject of subjects) {
        entries.push(getVerifiedSubjectSyllabus(board, classLevel, subject));
      }
    }
  }
  return entries;
}
